-- =============================================================================
-- V3：政策热点情报库（AI 与高校课程考核资讯 PRD）
-- 目标库：H2 2.4（文件模式），约定沿用 V1/V2：
--   1. 主键 BIGINT IDENTITY；时刻 TIMESTAMP WITH TIME ZONE；枚举存字符串 + CHECK。
--   2. 资讯按用户隔离（owner_id），与 tag/tasks 同一模式。
--   3. H2 不支持部分索引：凡查询常走的组合都建普通索引。
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 订阅来源（RSS 源 / 网页列表页）
-- 健康状态（最近抓取结果、连续失败计数）由采集管道维护，接口只读展示
-- -----------------------------------------------------------------------------
CREATE TABLE info_sources (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             BIGINT        NOT NULL,
    name                 VARCHAR(100)  NOT NULL,
    type                 VARCHAR(10)   NOT NULL,
    url                  VARCHAR(1000) NOT NULL,
    -- 网页类型的解析规则 JSON（item/title/link/published/content 选择器）；RSS 为 NULL
    parse_rule           CLOB,
    default_category     VARCHAR(20),
    enabled              BOOLEAN       NOT NULL DEFAULT TRUE,
    -- 健康状态
    last_fetch_at        TIMESTAMP WITH TIME ZONE,
    last_fetch_ok        BOOLEAN,
    last_fetch_message   VARCHAR(500),
    consecutive_failures INT           NOT NULL DEFAULT 0,
    -- 连续失败达阈值后停抓（PRD US-02 规则 3），需人工重新启用
    auto_disabled        BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_info_sources_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_info_sources_type CHECK (type IN ('RSS', 'WEBPAGE')),
    CONSTRAINT ck_info_sources_category CHECK (default_category IS NULL OR default_category IN ('POLICY', 'HOTSPOT', 'TECH', 'OTHER')),
    CONSTRAINT ck_info_sources_failures CHECK (consecutive_failures >= 0)
);

COMMENT ON TABLE info_sources IS '资讯订阅来源（RSS / 网页列表），按用户隔离';
COMMENT ON COLUMN info_sources.parse_rule IS '网页类型解析规则 JSON：item/title/link/published/content 选择器';
COMMENT ON COLUMN info_sources.auto_disabled IS '连续失败达阈值后停止自动抓取，重新启用由用户操作';

CREATE UNIQUE INDEX uq_info_sources_owner_name ON info_sources (owner_id, name);
CREATE INDEX ix_info_sources_owner_enabled ON info_sources (owner_id, enabled);

-- -----------------------------------------------------------------------------
-- 资讯条目
-- 去重：同一用户内 normalized_url 唯一（归一化规则见 UrlNormalizer）
-- 来源删除不级联删条目（PRD US-01 规则 3）：source_id 置空，靠 source_name 快照展示
-- -----------------------------------------------------------------------------
CREATE TABLE info_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id              BIGINT        NOT NULL,
    source_id             BIGINT,
    source_name           VARCHAR(100)  NOT NULL,
    title                 VARCHAR(500)  NOT NULL,
    url                   VARCHAR(1000) NOT NULL,
    normalized_url        VARCHAR(1000) NOT NULL,
    -- 只存提取后的正文文本（检索与 AI 用），不存 HTML 与图片（PRD 3.4 正文口径）
    content_text          CLOB,
    published_at          TIMESTAMP WITH TIME ZONE,
    category              VARCHAR(20),
    ai_summary            VARCHAR(1000),
    ai_key_points         CLOB,
    ai_suggested_category VARCHAR(20),
    ai_suggested_tags     VARCHAR(500),
    ai_status             VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    ai_error              VARCHAR(500),
    -- NULL = 未读；已读是用户动作，不是采集状态
    read_at               TIMESTAMP WITH TIME ZONE,
    starred               BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_info_items_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_info_items_source FOREIGN KEY (source_id) REFERENCES info_sources (id) ON DELETE SET NULL,
    CONSTRAINT ck_info_items_category CHECK (category IS NULL OR category IN ('POLICY', 'HOTSPOT', 'TECH', 'OTHER')),
    CONSTRAINT ck_info_items_ai_category CHECK (ai_suggested_category IS NULL OR ai_suggested_category IN ('POLICY', 'HOTSPOT', 'TECH', 'OTHER')),
    CONSTRAINT ck_info_items_ai_status CHECK (ai_status IN ('PENDING', 'PROCESSING', 'DONE', 'FAILED', 'SKIPPED'))
);

COMMENT ON TABLE info_items IS '资讯条目，按用户隔离，同用户内 normalized_url 去重';
COMMENT ON COLUMN info_items.source_name IS '来源名称快照：来源删除后仍可展示';
COMMENT ON COLUMN info_items.ai_key_points IS 'AI 要点，JSON 字符串数组';
COMMENT ON COLUMN info_items.ai_suggested_tags IS 'AI 建议标签名，JSON 字符串数组（采纳时映射到 tags 表）';
COMMENT ON COLUMN info_items.ai_status IS 'AI 处理状态：PENDING/PROCESSING/DONE/FAILED/SKIPPED';

CREATE UNIQUE INDEX uq_info_items_owner_url ON info_items (owner_id, normalized_url);
CREATE INDEX ix_info_items_owner_created ON info_items (owner_id, created_at);
CREATE INDEX ix_info_items_owner_source ON info_items (owner_id, source_id);
CREATE INDEX ix_info_items_owner_ai_status ON info_items (owner_id, ai_status);

-- -----------------------------------------------------------------------------
-- 资讯 × 标签：复用 tags 表（按 owner 隔离），与 task_tags 同构
-- -----------------------------------------------------------------------------
CREATE TABLE info_item_tags (
    info_item_id BIGINT NOT NULL,
    tag_id       BIGINT NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (info_item_id, tag_id),
    CONSTRAINT fk_info_item_tags_item FOREIGN KEY (info_item_id) REFERENCES info_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_info_item_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE
);

CREATE INDEX ix_info_item_tags_tag ON info_item_tags (tag_id);

-- -----------------------------------------------------------------------------
-- 资讯 → 任务关联（US-06 转任务）：一条资讯可多次转任务
-- 任务是软删（deleted_at），「任务已删除」的展示靠查询时过滤，外键不级联
-- -----------------------------------------------------------------------------
CREATE TABLE info_item_tasks (
    info_item_id BIGINT NOT NULL,
    task_id      BIGINT NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (info_item_id, task_id),
    CONSTRAINT fk_info_item_tasks_item FOREIGN KEY (info_item_id) REFERENCES info_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_info_item_tasks_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE RESTRICT
);

CREATE INDEX ix_info_item_tasks_task ON info_item_tasks (task_id);
