-- =============================================================================
-- V1：工作管理系统初始表结构
-- 目标库：H2 2.4（文件模式）
--
-- 约定：
--   1. 主键统一 BIGINT IDENTITY，与现有 Task 实体的 Long 保持一致。
--   2. 时刻用 TIMESTAMP WITH TIME ZONE，应用层用 Instant；只有「日期」语义的用 DATE。
--   3. 软删除用 deleted_at（NULL 表示未删除），查询一律带 deleted_at IS NULL。
--   4. 枚举存字符串并加 CHECK 约束；新增取值需要新的迁移脚本，不允许静默写入脏值。
--   5. 注意：H2 不支持部分索引（CREATE INDEX ... WHERE 会语法报错，已在 2.4.240 上实测），
--      因此凡是为软删查询服务的索引，都把 deleted_at 放在前导列，用它代替部分索引的过滤效果。
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 账号
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    -- 邮箱可选；H2 的唯一索引允许多行 NULL，所以不填邮箱的账号不会互相冲突
    email         VARCHAR(255),
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    -- 决定「今天」「本周」怎么算，周复盘的周期边界依赖它
    timezone      VARCHAR(64)  NOT NULL DEFAULT 'Asia/Shanghai',
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

COMMENT ON TABLE users IS '账号';
COMMENT ON COLUMN users.timezone IS 'IANA 时区名，影响「今日/本周」的计算';

-- 用户名不回收：注销（软删）后名字仍占用，否则无法保证唯一性
CREATE UNIQUE INDEX uq_users_username ON users (username);
CREATE UNIQUE INDEX uq_users_email ON users (email);

-- -----------------------------------------------------------------------------
-- 登录会话（刷新令牌）
-- 只存令牌的 SHA-256，不存明文；过期或登出置 revoked_at
-- -----------------------------------------------------------------------------
CREATE TABLE auth_refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    token_hash   VARCHAR(100) NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    user_agent   VARCHAR(255),
    client_ip    VARCHAR(45),
    last_used_at TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_auth_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_auth_refresh_tokens_hash ON auth_refresh_tokens (token_hash);
CREATE INDEX ix_auth_refresh_tokens_user ON auth_refresh_tokens (user_id, expires_at);

-- -----------------------------------------------------------------------------
-- 项目（Excel「项目/来源」里的项目一侧；来源用 tasks.source 自由文本）
-- 项目只归档、不删除，所以不需要 deleted_at
-- -----------------------------------------------------------------------------
CREATE TABLE projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    color       VARCHAR(16),
    sort_order  INT          NOT NULL DEFAULT 0,
    archived_at TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_projects_owner_name ON projects (owner_id, name);
CREATE INDEX ix_projects_owner ON projects (owner_id, archived_at);

-- -----------------------------------------------------------------------------
-- 任务（Excel「任务管理」表主体）
-- 有子任务：parent_task_id 自引用，层级由服务层限制（不做无限嵌套）
-- -----------------------------------------------------------------------------
CREATE TABLE tasks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            BIGINT       NOT NULL,
    project_id          BIGINT,
    parent_task_id      BIGINT,
    title               VARCHAR(200) NOT NULL,
    description         VARCHAR(4000),
    source              VARCHAR(100),
    -- 重要性 / 紧急性：艾森豪威尔矩阵的两个轴
    importance          VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM',
    urgency             VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM',
    -- 优先级：默认由 重要性 x 紧急性 推导，允许手工覆盖（覆盖后手工值优先）
    priority            VARCHAR(10)  NOT NULL DEFAULT 'P2',
    status              VARCHAR(20)  NOT NULL DEFAULT 'TODO',
    due_on              DATE,
    estimated_minutes   INT,
    -- 实际耗时的冗余累计值，与 task_time_logs 在同一事务内同步维护
    actual_minutes      INT          NOT NULL DEFAULT 0,
    -- AI 可替代？（三态：NULL=未评估 / TRUE / FALSE）；本轮为人工填写，不调模型
    ai_replaceable      BOOLEAN,
    ai_replacement_note VARCHAR(2000),
    next_action         VARCHAR(500),
    notes               VARCHAR(2000),
    completed_at        TIMESTAMP WITH TIME ZONE,
    sort_order          INT          NOT NULL DEFAULT 0,
    version             INT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_tasks_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    -- 项目不允许被静默删除：任务上的项目归属是有业务含义的数据
    CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tasks_parent FOREIGN KEY (parent_task_id) REFERENCES tasks (id) ON DELETE RESTRICT,
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'DOING', 'BLOCKED', 'DONE', 'CANCELLED')),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('P0', 'P1', 'P2', 'P3')),
    CONSTRAINT ck_tasks_importance CHECK (importance IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_tasks_urgency CHECK (urgency IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_tasks_estimated CHECK (estimated_minutes IS NULL OR estimated_minutes >= 0),
    CONSTRAINT ck_tasks_actual CHECK (actual_minutes >= 0),
    CONSTRAINT ck_tasks_not_own_parent CHECK (parent_task_id IS NULL OR parent_task_id <> id)
);

COMMENT ON TABLE tasks IS '任务（Excel 任务管理表）';
COMMENT ON COLUMN tasks.actual_minutes IS '实际耗时（分钟）冗余累计，权威数据在 task_time_logs';
COMMENT ON COLUMN tasks.ai_replaceable IS 'AI 可替代？NULL=未评估；本轮人工填写';

-- 看板/列表的主力索引：owner + 未删 + 状态 + 截止日
CREATE INDEX ix_tasks_owner_alive_status_due ON tasks (owner_id, deleted_at, status, due_on);
-- 今日视图：不按状态过滤，只看未删 + 截止日
CREATE INDEX ix_tasks_owner_alive_due ON tasks (owner_id, deleted_at, due_on);
CREATE INDEX ix_tasks_owner_project ON tasks (owner_id, project_id);
CREATE INDEX ix_tasks_owner_completed ON tasks (owner_id, completed_at);
CREATE INDEX ix_tasks_parent ON tasks (parent_task_id);

-- -----------------------------------------------------------------------------
-- 任务耗时明细（「任务记录」的落点：每一段实际投入都留一条流水）
-- ended_at 为 NULL 表示正在计时
-- -----------------------------------------------------------------------------
CREATE TABLE task_time_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT       NOT NULL,
    -- 冗余 owner：按人统计时不必回表 tasks
    owner_id   BIGINT       NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at   TIMESTAMP WITH TIME ZONE,
    -- 落库时算好的分钟数，避免每次聚合都做时间差
    minutes    INT          NOT NULL DEFAULT 0,
    source     VARCHAR(20)  NOT NULL DEFAULT 'TIMER',
    note       VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_time_logs_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_time_logs_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_task_time_logs_minutes CHECK (minutes >= 0),
    CONSTRAINT ck_task_time_logs_source CHECK (source IN ('TIMER', 'MANUAL')),
    CONSTRAINT ck_task_time_logs_order CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE INDEX ix_task_time_logs_task ON task_time_logs (task_id, started_at);
CREATE INDEX ix_task_time_logs_owner ON task_time_logs (owner_id, started_at);
-- 找「还在跑的计时」；H2 没有部分索引，这里用普通索引兜住
CREATE INDEX ix_task_time_logs_open ON task_time_logs (ended_at);

-- -----------------------------------------------------------------------------
-- 任务变更审计（只追加，不修改）
-- 只允许硬删任务时先归档这里：因此外键用 RESTRICT 而不是 CASCADE
-- -----------------------------------------------------------------------------
CREATE TABLE task_activity_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT       NOT NULL,
    actor_id   BIGINT,
    action     VARCHAR(30)  NOT NULL,
    field      VARCHAR(50),
    old_value  VARCHAR(500),
    new_value  VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_activity_logs_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_activity_logs_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE RESTRICT
);

COMMENT ON TABLE task_activity_logs IS '任务变更审计，只追加';

CREATE INDEX ix_task_activity_logs_task ON task_activity_logs (task_id, created_at);
CREATE INDEX ix_task_activity_logs_actor ON task_activity_logs (actor_id, created_at);

-- -----------------------------------------------------------------------------
-- 标签（任务与 AI 机会共用一套，按 owner 隔离）
-- 软删除时服务层把 name 改写为「原名称 (已删除 #id)」再置 deleted_at，
-- 以绕开 H2 没有部分唯一索引的限制（PostgreSQL 下可改成 WHERE deleted_at IS NULL 的部分索引）
-- -----------------------------------------------------------------------------
CREATE TABLE tags (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT      NOT NULL,
    name       VARCHAR(50) NOT NULL,
    color      VARCHAR(16),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_tags_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_tags_owner_name ON tags (owner_id, name);
CREATE INDEX ix_tags_owner_alive ON tags (owner_id, deleted_at);

CREATE TABLE task_tags (
    task_id    BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (task_id, tag_id),
    CONSTRAINT fk_task_tags_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE
);

CREATE INDEX ix_task_tags_tag ON task_tags (tag_id);

-- -----------------------------------------------------------------------------
-- 每日 AI 机会（Excel「每日AI机会」表）
-- 本轮只建表 + 只读接口，写入能力在阶段二接
-- -----------------------------------------------------------------------------
CREATE TABLE ai_opportunities (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             BIGINT        NOT NULL,
    occurred_on          DATE          NOT NULL,
    pain_point           VARCHAR(1000) NOT NULL,
    frequency            VARCHAR(20)   NOT NULL DEFAULT 'OCCASIONAL',
    ai_can_replace       VARCHAR(20)   NOT NULL DEFAULT 'UNKNOWN',
    replacement_approach VARCHAR(2000),
    minimal_experiment   VARCHAR(1000),
    status               VARCHAR(20)   NOT NULL DEFAULT 'CAPTURED',
    notes                VARCHAR(2000),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at           TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_ai_opportunities_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ai_opportunities_frequency CHECK (frequency IN ('DAILY', 'WEEKLY', 'MONTHLY', 'OCCASIONAL', 'ONE_OFF')),
    CONSTRAINT ck_ai_opportunities_replace CHECK (ai_can_replace IN ('YES', 'PARTIAL', 'NO', 'UNKNOWN')),
    CONSTRAINT ck_ai_opportunities_status CHECK (status IN ('CAPTURED', 'EXPERIMENTING', 'VALIDATED', 'DROPPED'))
);

COMMENT ON TABLE ai_opportunities IS '每日 AI 机会（Excel 每日AI机会表）';

CREATE INDEX ix_ai_opportunities_owner_date ON ai_opportunities (owner_id, deleted_at, occurred_on);
CREATE INDEX ix_ai_opportunities_owner_status ON ai_opportunities (owner_id, deleted_at, status);

CREATE TABLE opportunity_tags (
    opportunity_id BIGINT NOT NULL,
    tag_id         BIGINT NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (opportunity_id, tag_id),
    CONSTRAINT fk_opportunity_tags_opportunity FOREIGN KEY (opportunity_id) REFERENCES ai_opportunities (id) ON DELETE CASCADE,
    CONSTRAINT fk_opportunity_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE
);

CREATE INDEX ix_opportunity_tags_tag ON opportunity_tags (tag_id);

-- -----------------------------------------------------------------------------
-- Skill 库（Excel「Skill库」表）
-- 机会 -> Skill 的转化方向只保留一个：Skill 记住它来自哪个机会，
-- 机会侧不存反向字段，避免双向写不一致
-- -----------------------------------------------------------------------------
CREATE TABLE skills (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id               BIGINT       NOT NULL,
    name                   VARCHAR(200) NOT NULL,
    trigger_scenario       VARCHAR(1000),
    input_spec             VARCHAR(2000),
    output_spec            VARCHAR(2000),
    -- 提示词/步骤可能很长，用 CLOB（迁移到 PostgreSQL 时对应 TEXT）
    prompt_or_steps        CLOB,
    status                 VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    -- 已节省时间的冗余累计值，权威数据在 skill_usage_logs
    saved_minutes_total    INT          NOT NULL DEFAULT 0,
    usage_count            INT          NOT NULL DEFAULT 0,
    next_improvement       VARCHAR(1000),
    source_opportunity_id  BIGINT,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at             TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_skills_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_skills_source_opportunity FOREIGN KEY (source_opportunity_id) REFERENCES ai_opportunities (id) ON DELETE RESTRICT,
    CONSTRAINT ck_skills_status CHECK (status IN ('DRAFT', 'ACTIVE', 'DEPRECATED')),
    CONSTRAINT ck_skills_saved CHECK (saved_minutes_total >= 0),
    CONSTRAINT ck_skills_usage CHECK (usage_count >= 0)
);

COMMENT ON TABLE skills IS 'Skill 库（Excel Skill库表）';
COMMENT ON COLUMN skills.saved_minutes_total IS '已节省时间（分钟）冗余累计，权威数据在 skill_usage_logs';

CREATE INDEX ix_skills_owner_status ON skills (owner_id, deleted_at, status);
CREATE INDEX ix_skills_source_opportunity ON skills (source_opportunity_id);

-- -----------------------------------------------------------------------------
-- Skill 使用流水（支撑「已节省时间」可核对，而不是一个凭空的数字）
-- -----------------------------------------------------------------------------
CREATE TABLE skill_usage_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id     BIGINT      NOT NULL,
    owner_id     BIGINT      NOT NULL,
    used_on      DATE        NOT NULL,
    saved_minutes INT        NOT NULL,
    task_id      BIGINT,
    note         VARCHAR(500),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_skill_usage_logs_skill FOREIGN KEY (skill_id) REFERENCES skills (id) ON DELETE CASCADE,
    CONSTRAINT fk_skill_usage_logs_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_usage_logs_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE SET NULL,
    CONSTRAINT ck_skill_usage_logs_saved CHECK (saved_minutes >= 0)
);

CREATE INDEX ix_skill_usage_logs_skill ON skill_usage_logs (skill_id, used_on);
CREATE INDEX ix_skill_usage_logs_owner ON skill_usage_logs (owner_id, used_on);

-- -----------------------------------------------------------------------------
-- 周复盘（Excel「周复盘」表）
-- 统计数字是「生成那一刻的快照」，不随后续补录的任务变化；
-- 需要实时数字走 /api/stats 接口现算，两者语义不同，不要混用
-- -----------------------------------------------------------------------------
CREATE TABLE weekly_reviews (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id                    BIGINT      NOT NULL,
    -- ISO-8601 周，例如 2026-W42
    week_key                    VARCHAR(10) NOT NULL,
    period_start                DATE        NOT NULL,
    period_end                  DATE        NOT NULL,
    completed_task_count        INT         NOT NULL DEFAULT 0,
    captured_opportunity_count  INT         NOT NULL DEFAULT 0,
    landed_skill_count          INT         NOT NULL DEFAULT 0,
    saved_minutes_total         INT         NOT NULL DEFAULT 0,
    biggest_friction            VARCHAR(2000),
    next_experiment             VARCHAR(2000),
    notes                       VARCHAR(2000),
    generated_by                VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    generated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_weekly_reviews_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_weekly_reviews_generated_by CHECK (generated_by IN ('AUTO', 'MANUAL')),
    CONSTRAINT ck_weekly_reviews_period CHECK (period_end >= period_start)
);

COMMENT ON TABLE weekly_reviews IS '周复盘（Excel 周复盘表），统计字段为生成时快照';

CREATE UNIQUE INDEX uq_weekly_reviews_owner_week ON weekly_reviews (owner_id, week_key);
CREATE INDEX ix_weekly_reviews_period ON weekly_reviews (owner_id, period_start);
